import uuid

from pgvector.sqlalchemy import Vector
from sqlalchemy import Computed, ForeignKey, Integer, String, Text, UniqueConstraint
from sqlalchemy.dialects.postgresql import TSVECTOR, UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base, CreatedAtMixin, UUIDPKMixin
from app.models.embedding import EMBEDDING_DIM


class KBChunk(UUIDPKMixin, CreatedAtMixin, Base):
    """A section-based chunk of a KB article (migration 0012, Blueprint §12.1). `tsv` is
    generated by PostgreSQL from `text` for keyword search; `embedding` is for dense
    search. Hybrid retrieval (Week 4) fuses both."""

    __tablename__ = "kb_chunks"
    __table_args__ = (UniqueConstraint("knowledge_base_id", "chunk_index", name="uq_kb_chunks_article_index"),)

    knowledge_base_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("knowledge_base.id", ondelete="CASCADE"), nullable=False, index=True
    )
    chunk_index: Mapped[int] = mapped_column(Integer(), nullable=False)
    sections: Mapped[str] = mapped_column(String(128), nullable=False)
    text: Mapped[str] = mapped_column(Text(), nullable=False)
    n_tokens: Mapped[int] = mapped_column(Integer(), nullable=False)
    embedding: Mapped[list[float]] = mapped_column(Vector(EMBEDDING_DIM), nullable=False)
    tsv: Mapped[str] = mapped_column(TSVECTOR(), Computed("to_tsvector('english', text)", persisted=True))
